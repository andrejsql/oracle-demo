CREATE TABLE IF NOT EXISTS customers (
cust_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
first_name     VARCHAR2(100) ,
last_name      VARCHAR2(100) ,
email          VARCHAR2(300) ,
is_premium     BOOLEAN,
is_active      BOOL,  
last_upd1      TIMESTAMP    DEFAULT SYSTIMESTAMP,
last_upd2      TIMESTAMP    DEFAULT ON NULL FOR INSERT ONLY SYSTIMESTAMP,
last_upd3      TIMESTAMP    DEFAULT ON NULL FOR INSERT AND UPDATE SYSTIMESTAMP 
 );
 
