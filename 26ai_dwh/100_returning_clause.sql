-------------------------------------------------------------------------------
--   RETURNING with MERGE
-------------------------------------------------------------------------------

DECLARE
  TYPE id_tab     IS TABLE OF customers.cust_id%TYPE;
  TYPE limit_tab  IS TABLE OF customers.credit_limit%TYPE;

  l_ids       id_tab;
  l_old_limit limit_tab;
  l_new_limit limit_tab;
BEGIN
  MERGE INTO customers c
  USING (
    SELECT 'john.miller@example.com' AS email
         , 'John'                    AS first_name
         , 'Miller'                  AS last_name
         , TRUE                      AS is_premium
         , TRUE                      AS is_active
         , 2000                      AS credit_limit
    FROM dual
    UNION ALL
    SELECT 'sue.parker@example.com'
         , 'Sue'
         , 'Parker'
         , FALSE
         , TRUE
         , 1500
    FROM dual
  ) s
  ON (c.email = s.email)
  WHEN MATCHED THEN
    UPDATE SET c.first_name   = s.first_name
             , c.last_name    = s.last_name
             , c.is_premium   = s.is_premium
             , c.is_active    = s.is_active
             , c.credit_limit = s.credit_limit
             , c.last_upd     = SYSTIMESTAMP
  WHEN NOT MATCHED THEN
    INSERT (
      first_name
    , last_name
    , email
    , is_premium
    , is_active
    , credit_limit
    )
    VALUES (
      s.first_name
    , s.last_name
    , s.email
    , s.is_premium
    , s.is_active
    , s.credit_limit
    )
  RETURNING NEW cust_id
          , OLD credit_limit
          , NEW credit_limit
  BULK COLLECT INTO
            l_ids
          , l_old_limit
          , l_new_limit;

  FOR i IN 1 .. l_ids.COUNT LOOP
    DBMS_OUTPUT.PUT_LINE(
      'cust_id=' || l_ids(i) ||
      ', old_limit=' || NVL(TO_CHAR(l_old_limit(i)), 'null') ||
      ', new_limit=' || NVL(TO_CHAR(l_new_limit(i)), 'null')
    );
  END LOOP;
END;
