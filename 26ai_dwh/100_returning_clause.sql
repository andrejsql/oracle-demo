-------------------------------------------------------------------------------
--   Using bulk collect for multi-row DML
-------------------------------------------------------------------------------

DECLARE
  TYPE id_tab     IS TABLE OF customers.cust_id%TYPE;
  TYPE limit_tab  IS TABLE OF customers.credit_limit%TYPE;

  l_ids       id_tab;
  l_old_limit limit_tab;
  l_new_limit limit_tab;
BEGIN
  UPDATE customers
  SET    credit_limit = credit_limit + 250,
         last_upd     = SYSTIMESTAMP
  WHERE  is_active = TRUE
  RETURNING cust_id
          , OLD credit_limit
          , NEW credit_limit
  BULK COLLECT INTO
            l_ids
          , l_old_limit
          , l_new_limit;

  FOR i IN 1 .. l_ids.COUNT LOOP
    DBMS_OUTPUT.PUT_LINE(
      'cust_id=' || l_ids(i) ||
      ', old='   || l_old_limit(i) ||
      ', new='   || l_new_limit(i)
    );
  END LOOP;
END;
