-------------------------------------------------------------------------------
--   Using OLD and NEW with UPDATE
-------------------------------------------------------------------------------

DECLARE
  l_old_limit  customers.credit_limit%TYPE;
  l_new_limit  customers.credit_limit%TYPE;
BEGIN
  UPDATE customers
  SET    credit_limit = credit_limit * 1.15,
         last_upd     = SYSTIMESTAMP
  WHERE  email = 'john.miller@example.com'
  RETURNING OLD credit_limit
          , NEW credit_limit
  INTO      l_old_limit
          , l_new_limit;

  DBMS_OUTPUT.PUT_LINE(
    'old_limit=' || l_old_limit || ', new_limit=' || l_new_limit
  );
END;
