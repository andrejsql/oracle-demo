--   Using aggregate functions
-------------------------------------------------------------------------------

DECLARE
  l_avg_old  NUMBER;
  l_avg_new  NUMBER;
BEGIN
  UPDATE customers
  SET    credit_limit = credit_limit * 1.10,
         last_upd     = SYSTIMESTAMP
  WHERE  is_active = TRUE
  RETURNING AVG(OLD credit_limit)
          , AVG(NEW credit_limit)
  INTO      l_avg_old
          , l_avg_new;

  DBMS_OUTPUT.PUT_LINE(
    'avg old=' || l_avg_old || ', avg new=' || l_avg_new
  );
END;
