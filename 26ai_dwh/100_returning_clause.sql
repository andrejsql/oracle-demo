-------------------------------------------------------------------------------
--   Only single-row INSERT (not with INSERT..SELECT)
-------------------------------------------------------------------------------

DECLARE
  l_cust_id   customers.cust_id%TYPE;
  l_last_upd  customers.last_upd%TYPE;
BEGIN
  INSERT INTO customers (
    first_name
  , last_name
  , email
  , is_premium
  , is_active
  , credit_limit
  )
  VALUES (
    'John'
  , 'Miller'
  , 'john.miller@example.com'
  , TRUE
  , TRUE
  , 1000
  )
  RETURNING NEW cust_id
          , NEW last_upd
  INTO      l_cust_id
          , l_last_upd;

  DBMS_OUTPUT.PUT_LINE(
    'cust_id=' || l_cust_id || ', last_upd=' || TO_CHAR(l_last_upd, 'YYYY-MM-DD HH24:MI:SS')
  );
END;
