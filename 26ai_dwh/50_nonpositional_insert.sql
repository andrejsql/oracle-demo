-------------------------------------------------------------------------------
--    INSERT SET: column = value pairs, like UPDATE SET.
--    Order-independent, no parallel lists to keep in sync.
--    Also supports multi-row inserts in a single statement.
-------------------------------------------------------------------------------

INSERT INTO customers
SET    first_name = 'Lena'
,      last_name  = 'Kraemer'
,      email      = 'lena.kraemer@yahoo.com';

INSERT INTO customers SET 
  (first_name = 'Adrian', last_name = 'Nolan', email = 'adrian22@gmail.com')
, (first_name = 'Maya', last_name = 'Santoro', email = 'Santoro987@yahoo.com');

COMMIT;

SELECT cust_id, first_name, last_name, email, is_premium, is_active
