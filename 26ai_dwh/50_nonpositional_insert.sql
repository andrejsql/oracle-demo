-------------------------------------------------------------------------------
--    INSERT SELECT maps by position: the nth SELECT column goes into the
--    nth table column. customers2 has last_name/first_name in reverse order -
--    the data will land in the wrong columns with no error.
-------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS customers2
AS 
SELECT cust_id, last_name, first_name,  email, is_premium, is_active, last_upd
FROM   customers 
WHERE  1=2;

INSERT INTO customers2 
SELECT *
FROM customers; 

-------------------------------------------------------------------------------
--    first_name and last_name are swapped because customers2 column order differs.
-------------------------------------------------------------------------------

SELECT cust_id, first_name, last_name, email, is_premium, is_active
FROM   customers2 ; 
 
pause Press Enter TO CONTINUE

ROLLBACK;

-------------------------------------------------------------------------------
--    INSERT BY NAME: Oracle matches SELECT output to target columns by name,
--    not position. Column order in the SELECT no longer matters.
-------------------------------------------------------------------------------

INSERT INTO customers2 BY NAME
SELECT *
FROM customers; 

SELECT cust_id, first_name, last_name, email, is_premium, is_active
FROM   customers2 ; 

pause Press Enter TO CONTINUE

ROLLBACK;

-------------------------------------------------------------------------------
--    BY NAME routes by the SELECT output name - aliases included.
--    Here last_name is aliased AS first_name, so it lands in first_name.
--    Intentional here; in production, wrong aliases silently misdirect data.
-------------------------------------------------------------------------------

INSERT INTO customers2 BY NAME
SELECT '!'||last_name as first_name
,      cust_id
,      is_active
,      email
,      '!'||first_name as last_name
,      is_premium
FROM   customers; 

SELECT cust_id, first_name, last_name, email, is_premium, is_active
FROM   customers2 ; 


